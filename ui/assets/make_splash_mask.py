#!/usr/bin/env python3
"""Builds the splash logo masks: ui/splash_logo.c (412 x 412 screen) and ui/splash_logo_360.c (360 x 360 screen).

The logo is one color on a flat background, so only its shape is stored: an 8-bit mask cropped to the logo's bounding box, drawn in the
current theme's color on the theme's background. That is far less to draw and send to the panel than a full-screen picture, and it
follows the theme. Run from the project folder:  python3 ui/assets/make_splash_mask.py
"""
import numpy as np
from PIL import Image

SRC = "ui/assets/splash-source.png"      # 1024 x 1024: the cream logo on the petrol background
PAD = 6                                  # source pixels of margin around the logo

a = np.asarray(Image.open(SRC).convert("RGB")).astype(np.float64)
bg = a[2, 2]
dist = np.linalg.norm(a - bg, axis=2)
solid = a[dist > 0.5 * dist.max()].reshape(-1, 3).astype(np.uint8)
colors, counts = np.unique(solid, axis=0, return_counts=True)
logo = colors[counts.argmax()].astype(np.float64)               # the logo's own color: the most common one that is not the background
d = logo - bg
alpha = np.clip(((a - bg) @ d) / (d @ d), 0, 1)
ys, xs = np.nonzero(alpha > 0.01)
x0, x1 = max(xs.min() - PAD, 0), min(xs.max() + 1 + PAD, a.shape[1])
y0, y1 = max(ys.min() - PAD, 0), min(ys.max() + 1 + PAD, a.shape[0])
mask = Image.fromarray((alpha[y0:y1, x0:x1] * 255 + 0.5).astype(np.uint8))
print(f"logo color {tuple(int(round(c)) for c in logo)} on {tuple(int(c) for c in bg)}; box {x1 - x0} x {y1 - y0} at {x0},{y0} of {a.shape[1]}")

for size in (412, 360):
    s = size / a.shape[1]
    w, h = round((x1 - x0) * s), round((y1 - y0) * s)
    m = np.asarray(mask.resize((w, h), Image.LANCZOS))
    data = m.tobytes()
    rows = ["    " + ",".join(f"0x{b:02X}" for b in data[i:i + 32]) + "," for i in range(0, len(data), 32)]
    text = f"""/* Generated by assets/make_splash_mask.py from splash-source.png: the splash logo's shape as an 8-bit mask, {w} x {h}, for the {size} x {size} screen.
 * It is drawn in the theme's logo color. nav_splash_logo_x/y: where its top-left corner sits on the screen. */
#include "lvgl.h"

static const uint8_t splash_logo_map[] = {{
""" + "\n".join(rows) + f"""
}};

const int nav_splash_logo_x = {round(x0 * s)};
const int nav_splash_logo_y = {round(y0 * s)};

const lv_image_dsc_t nav_splash_logo = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_A8,
        .w = {w},
        .h = {h},
        .stride = {w},
    }},
    .data_size = sizeof(splash_logo_map),
    .data = splash_logo_map,
}};
"""
    name = "ui/splash_logo.c" if size == 412 else f"ui/splash_logo_{size}.c"
    open(name, "w").write(text)
    print(f"  {name}: {w} x {h} mask at {round(x0 * s)},{round(y0 * s)} ({len(data)} bytes)")
