"""Speaks the display's phrases with the Mac's text-to-speech and writes board_voices.c (24 kHz, 16-bit mono PCM).
usage: python3 make_voices.py [voice]    (default Samantha; `say -v '?'` lists voices)"""
import subprocess, sys, struct, wave, os, tempfile
VOICE = sys.argv[1] if len(sys.argv) > 1 else "Samantha"
PHRASES = [("power_on", "Power on"), ("connected", "Connected"), ("disconnected", "Disconnected"), ("lets_go", "Let's go!")]
RATE = 24000
here = os.path.dirname(os.path.abspath(__file__))

def speak(text):
    d = tempfile.mkdtemp()
    aiff, wav = os.path.join(d, "v.aiff"), os.path.join(d, "v.wav")
    subprocess.run(["say", "-v", VOICE, "-o", aiff, text], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1", aiff, wav], check=True)
    w = wave.open(wav)
    raw = w.readframes(w.getnframes())
    s = list(struct.unpack("<%dh" % (len(raw) // 2), raw))
    thresh = 400                                           # trim leading and trailing silence
    a = next((i for i, v in enumerate(s) if abs(v) > thresh), 0)
    b = len(s) - next((i for i, v in enumerate(reversed(s)) if abs(v) > thresh), 0)
    s = s[max(0, a - 120):min(len(s), b + 240)]
    peak = max(abs(v) for v in s) or 1
    return [int(v * 30000 / peak) for v in s]              # normalize to a fixed loudness; volume is applied on the board

out = ['/* Generated by voices/make_voices.py (voice: %s). 24 kHz, 16-bit mono. */' % VOICE,
       '#include "board_voices.h"', '']
total = 0
for name, text in PHRASES:
    s = speak(text)
    total += len(s)
    out.append(f"static const int16_t v_{name}[] = {{")
    for i in range(0, len(s), 16):
        out.append("    " + ",".join(str(v) for v in s[i:i + 16]) + ",")
    out.append("};")
    out.append(f"const voice_t voice_{name} = {{ v_{name}, {len(s)} }};   /* \"{text}\", {len(s) / RATE:.2f} s */")
    out.append("")
    print(f'{name}: "{text}" {len(s) / RATE:.2f} s')
open(os.path.join(here, "..", "board_voices.c"), "w").write("\n".join(out))
open(os.path.join(here, "..", "board_voices.h"), "w").write(
    '#ifndef BOARD_VOICES_H\n#define BOARD_VOICES_H\n#include <stdint.h>\n#define VOICE_RATE %d\n'
    'typedef struct { const int16_t *pcm; int samples; } voice_t;\n'
    'extern const voice_t voice_power_on;\nextern const voice_t voice_connected;\nextern const voice_t voice_disconnected;\nextern const voice_t voice_lets_go;\n#endif\n' % RATE)
print("total %.1f KB" % (total * 2 / 1024))
